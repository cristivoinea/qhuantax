from __future__ import annotations
from typing import Union, Sequence, Optional, Tuple
import numpy as np
import jax
import jax.numpy as jnp
from functools import partial
import quantax as qtx
from quantax.global_defs import PARTICLE_TYPE, get_sites, get_lattice, get_default_dtype


_Identity = None
_Z2Inverse = dict()


@jax.jit
@partial(jax.vmap, in_axes=(None, 0, 0))
def _permutation_sign(
    spins: jax.Array, perm: jax.Array, perm_sign: jax.Array
) -> jax.Array:
    """Compute the permutation sign. This function will be slow if Nparticles is None"""
    perm = jnp.argsort(perm)  # invert permmutation

    Ntotal = get_sites().Ntotal
    if Ntotal is None:
        Nmodes = jnp.max(perm) + 1
        perm = jnp.where(spins > 0, perm, Nmodes)
        arg = jnp.argsort(perm == Nmodes, stable=True)
        perm = perm[arg]
    else:
        indices = jnp.flatnonzero(spins > 0, size=Ntotal)
        perm = perm[indices]

    compare = perm[None, :] > perm[:, None]
    compare = compare[jnp.tril_indices_from(compare, k=-1)]
    sign = jnp.where(jnp.sum(compare) % 2, -1, 1)

    additional_sign = jnp.sum((spins > 0) & (perm_sign < 0))
    perm_sign = jnp.where(additional_sign % 2 == 0, 1, -1).astype(perm_sign.dtype)
    return sign * perm_sign


class FuzzySphereSymmetry (qtx.symmetry.Symmetry):
    
    def __init__(
        self,
        generator: Optional[np.ndarray] = None,
        sector: Union[int, Sequence] = 0,
        generator_sign: Optional[np.ndarray] = None,
        Z2_inversion: int = 0,
        perm: Optional[jax.Array] = None,
        character: Optional[jax.Array] = None,
        perm_sign: Optional[jax.Array] = None,
        ph_sign: Optional[bool] = False,
    ):
            self._ph_sign = ph_sign
            super().__init__(generator, sector, generator_sign, Z2_inversion, perm, character, perm_sign)


    @partial(jax.jit, static_argnums=0)
    def symmetrize(self, psi: qtx.utils.PsiArray, spins: Optional[jax.Array] = None) -> qtx.utils.PsiArray:
        r"""
        Symmetrize the wavefunction as

        .. math::

            \psi^{\mathrm{symm}}(s) = \frac{d}{|G|} \sum_g \mathrm{sign}(s, g) \chi_g \psi(T_g s),
        
        where :math:`d` is the dimension of the group representation,
        :math:`|G|` is the number of elements in the symmetry group, and
        :math:`\mathrm{sign}(s, g)` is the additional sign generated by the symmetry
        depending on the input Fock state (only for fermionic systems).

        :param psi:
            Wavefunctions :math:`\psi(T_i s)`.

        :param spins:
            Input spin or fermion configuration :math:`s`.
            This is only necessary in fermionic systems, where additional
            minus signs :math:`\mathrm{sign}(s, g)` can be generated by the symmetry.

        :return:
            The symmetrized wave function

        .. note::

            This function is jittable.
        """
        if psi.ndim > 1:
            raise ValueError(
                f"Input wavefunction should be 1D, got dimension {psi.ndim}"
            )
        if spins is not None and spins.ndim > 1:
            raise ValueError(f"Input spins should be 1D, got dimension {spins.ndim}")

        if self.is_fermion:
            if spins is None:
                raise RuntimeError(
                    "`symmetrize` can't be performed without input fermion states."
                )
            sign = _permutation_sign(spins, self._perm, self._perm_sign)
            character = sign * self._character
        else:
            character = self._character

        if self.Z2_inversion != 0:
            character = jnp.concatenate([character, self.Z2_inversion * character])
        character = (character * character[0] / character.size).astype(psi.dtype)
        
        if self._ph_sign:
            spins_symm = self.get_symm_spins(spins)
            nperm = spins_symm.shape[0]
            ph_signs_vect = jnp.where( jnp.arange(nperm) < nperm//2, 1, (-1)**(jnp.count_nonzero(spins_symm[jnp.arange(nperm),self.Nsites:] == 1, axis=1)))
            character *= ph_signs_vect
                
        return (psi * character).sum()


    def __matmul__(self, other: FuzzySphereSymmetry) -> FuzzySphereSymmetry:
        r"""
        Generate superposition of two symmetries.

        .. code-block:: python

            from quantax.sites import Square
            from quantax.symmetry import Translation

            lattice = Square(4)
            trans1 = Translation((1, 0))  # translation symmetry in x axis
            trans2 = Translation((0, 1))  # translation symmetry in y axis
            trans2D = trans1 @ trans2  # 2D translation symmetry

        .. warning::
            Users are responsible to ensure the compatibility of different symmetries,
            especially if their generators don't commute.
        """
        generator = np.concatenate([self._generator, other._generator], axis=0)
        sector = [*self._sector, *other._sector]
        g_sign = np.concatenate([self._generator_sign, other._generator_sign], axis=0)
        perm = self._perm[:, other._perm].reshape(-1, self.Nmodes)
        character = jnp.einsum("i,j->ij", self._character, other._character).flatten()
        p_sign = jnp.einsum("is,js->ijs", self._perm_sign, other._perm_sign)
        p_sign = p_sign.reshape(-1, self.Nmodes)
        ph_sign = self._ph_sign | other._ph_sign

        if self.Z2_inversion == 0:
            Z2_inversion = other.Z2_inversion
        elif other.Z2_inversion == 0:
            Z2_inversion = self.Z2_inversion
        elif self.Z2_inversion == other.Z2_inversion:
            Z2_inversion = self.Z2_inversion
        else:
            raise ValueError("Symmetry with different Z2_inversion can't be added")

        new_symm = FuzzySphereSymmetry(
            generator, sector, g_sign, Z2_inversion, perm, character, p_sign, ph_sign
        )
        return new_symm


def IdentityQH() -> FuzzySphereSymmetry:
    """Identity (no symmetry)."""
    global _Identity
    if _Identity is None:
        _Identity = FuzzySphereSymmetry()
    return _Identity


def ParticleHoleQH(eigval: int = 1) -> FuzzySphereSymmetry:
    """
    Particle-hole symmetry for fermion systems.

    :param eigval:
        An integer specifying the symmetry sector. The meaning of each number is

        - 1: Eigenvalue 1 after particle-hole inversion
        - 0: No particle-hole inversion
        - -1: Eigenvalue -1 after particle-hole inversion
    """
    if eigval not in (1, -1):
        raise ValueError("'eigval' of Z2Inversion should be 1 or -1.")
    N = get_sites().Nsites
    generator = np.concatenate([np.arange(N, 2 * N), np.arange(N)])
    global _Z2Inverse
    if eigval not in _Z2Inverse:
        _Z2Inverse[eigval] = FuzzySphereSymmetry(Z2_inversion=eigval, ph_sign=True)
    return _Z2Inverse[eigval]
    

def _map_sign(spins: jax.Array, perm: jax.Array, mode_sign: jax.Array, inverting: bool) -> jax.Array:
    r"""The sign :math:`\sigma` in :math:`U|t\rangle = \sigma|t'\rangle` for a configuration ``spins`` = :math:`t'`
    reached by one map: :math:`U c^\dagger_o U^{-1} = a_o c^\dagger_{\pi(o)}`, or :math:`a_o c_{\pi(o)}` with
    :math:`U|0\rangle = |\text{all modes filled}\rangle` when ``inverting``, in quantax's mode order. ``perm`` is an
    involution, so the preimage :math:`t` has its particles on :math:`\pi(\text{occupied}(t'))` (inverting: on the
    complement). For the occupied modes :math:`o_1<\dots<o_n` of :math:`t`, :math:`\sigma=\prod a_{o_i}` times the
    parity of the sequence :math:`\pi(o_i)`, and for an inverting map times :math:`(-1)^{\sum_i \pi(o_i)}`."""
    Ntotal = get_sites().Ntotal
    pre = -spins[perm] if inverting else spins[perm]           # the preimage t
    occ = jnp.flatnonzero(pre > 0, size=Ntotal)
    p = perm[occ]
    parity = jnp.sum(jnp.triu(p[:, None] > p[None, :], 1)) + jnp.sum(mode_sign[occ] < 0)
    if inverting:
        parity = parity + jnp.sum(p)
    return jnp.where(parity % 2 == 0, 1, -1)


class FermionMapSymmetry(FuzzySphereSymmetry):
    r"""The group generated by commuting involutive fermionic maps, each :math:`U c^\dagger_o U^{-1} = a_o
    c^\dagger_{\pi(o)}` or, for a particle-hole map, :math:`a_o c_{\pi(o)}` with :math:`U|0\rangle =
    |\text{full}\rangle`. Every image carries its exact fermionic sign, computed per configuration (``_map_sign``), so
    particle-hole maps need no special casing. Build it from ``Z2QH``, ``RyQH``, ``PHQH`` and combine with ``@``;
    ``fuzzy_sphere_symmetry`` does both. Checked against FuzzifiED's (P, Z, R) sectors at N=8.

    The symmetrized amplitude is :math:`\psi_\text{sym}(s)=\frac{1}{|G|}\sum_g\chi_g\langle s|U_g|\psi\rangle`, the
    projector onto the sector with the given eigenvalues.
    """

    def __init__(self, maps: Sequence[Tuple[np.ndarray, np.ndarray, bool]] = (), eigvals: Sequence[int] = (),
                 names: Sequence[str] = ()):
        super().__init__()
        # (perm, mode signs, inverting, eps): an inverting map has U|0> = eps |full>, |full> in quantax's mode order
        self._maps = tuple((jnp.asarray(m[0], jnp.int32), jnp.asarray(m[1], jnp.int8), bool(m[2]),
                            int(m[3]) if len(m) > 3 else 1) for m in maps)
        self._eigvals = tuple(int(e) for e in eigvals)
        self._names = tuple(names)
        k = len(self._maps)
        self._elements = [tuple(bool((e >> i) & 1) for i in range(k)) for e in range(2 ** k)]
        self._chars = np.array([np.prod([ev for ev, used in zip(self._eigvals, el) if used]) for el in self._elements],
                               dtype=float)

    @property
    def nsymm(self) -> int:
        return len(self._elements)

    @property
    def sectors(self) -> dict:
        """The eigenvalue of each map, e.g. ``{"Z2": 1, "Ry": 1}``."""
        return dict(zip(self._names, self._eigvals))

    @property
    def basis(self):
        raise NotImplementedError("FermionMapSymmetry has no QuSpin basis: use it for variational states, and "
                                  "LzUserBasisSymmetry for dense ones")

    def images(self, spins: jax.Array):
        """Image t of ``spins`` under every group element (identity first) and the sign of <spins|U_g|t>."""
        images, signs = [], []
        for el in self._elements:
            t, sign = spins, 1
            for (perm, a, inverting, eps), used in zip(self._maps, el):
                if used:
                    t = -t[perm] if inverting else t[perm]
                    sign = sign * _map_sign(t, perm, a, inverting) * (eps if inverting else 1)
            images.append(t)
            signs.append(sign)
        return jnp.stack(images), jnp.stack(jnp.asarray(signs))

    def get_symm_spins(self, spins: jax.Array) -> jax.Array:
        if spins.ndim > 1:
            raise ValueError(f"Input spins should be 1D, got dimension {spins.ndim}")
        return self.images(spins)[0]

    @partial(jax.jit, static_argnums=0)
    def symmetrize(self, psi: qtx.utils.PsiArray, spins: Optional[jax.Array] = None) -> qtx.utils.PsiArray:
        if spins is None:
            raise RuntimeError("`symmetrize` needs the input fermion configuration for the fermionic signs.")
        signs = self.images(spins)[1]
        weights = (jnp.asarray(self._chars) * signs / self.nsymm).astype(psi.dtype)
        return (psi * weights).sum()

    def __matmul__(self, other: FermionMapSymmetry) -> FermionMapSymmetry:
        if not isinstance(other, FermionMapSymmetry):
            raise TypeError("FermionMapSymmetry combines only with another FermionMapSymmetry")
        return FermionMapSymmetry([*self._raw_maps(), *other._raw_maps()], [*self._eigvals, *other._eigvals],
                                  [*self._names, *other._names])

    def _raw_maps(self):
        return [(np.asarray(p), np.asarray(a), inv, eps) for p, a, inv, eps in self._maps]


def _check_eigval(eigval: int):
    if eigval not in (1, -1):
        raise ValueError(f"symmetry eigenvalue must be 1 or -1, got {eigval}")


def Z2QH(eigval: int) -> FermionMapSymmetry:
    r"""Ising :math:`\mathbb{Z}_2`, the flavour exchange :math:`c^\dagger_{m\uparrow}\leftrightarrow
    c^\dagger_{m\downarrow}` (FuzzifiED ``GetFlavPermQNOffd(nm, 2, [2, 1])``; the same as ``FlavourPermQH``)."""
    _check_eigval(eigval)
    N = get_sites().Nsites
    flip = np.concatenate([np.arange(N, 2 * N), np.arange(N)])
    return FermionMapSymmetry([(flip, np.ones(2 * N), False)], [eigval], ["Z2"])


def RyQH(eigval: int) -> FermionMapSymmetry:
    r"""The :math:`\pi` rotation about the y axis, :math:`c^\dagger_{mf}\mapsto(-1)^{m+s}c^\dagger_{-mf}` (FuzzifiED
    ``GetRotyQNOffd``). At :math:`L_z=0` its eigenvalue is :math:`(-1)^L`: +1 keeps the even-L states."""
    _check_eigval(eigval)
    N = get_sites().Nsites
    j = np.arange(2 * N) % N
    mirror = (np.arange(2 * N) // N) * N + (N - 1 - j)
    return FermionMapSymmetry([(mirror, (-1) ** j, False)], [eigval], ["Ry"])


def _ph_phase(N: int) -> int:
    """The sign between the filled states in FuzzifiED's mode order (orbital-major) and quantax's (flavour-major)."""
    return (-1) ** (N * (N - 1) // 2)


def PHQH(eigval: int) -> FermionMapSymmetry:
    r"""The particle-hole symmetry of the fuzzy-sphere Ising model, PRX 13, 021009:
    :math:`c^\dagger_{m\uparrow}\mapsto -c_{m\downarrow}`, :math:`c^\dagger_{m\downarrow}\mapsto c_{m\uparrow}`
    (FuzzifiED ``GetParityQNOffd(nm, 2, [2, 1], [-1, 1])``), with :math:`U|0\rangle=|\text{full}\rangle` in
    FuzzifiED's orbital-major mode order, i.e. :math:`(-1)^{N(N-1)/2}|\text{full}\rangle` in quantax's flavour-major
    one (``_ph_phase``): the vacuum and the Ising ground state are +1 at every N, as in FuzzifiED. Requires half
    filling."""
    _check_eigval(eigval)
    sites = get_sites()
    N = sites.Nsites
    if sites.Ntotal != N:
        raise ValueError("particle-hole needs half filling (N particles in 2N modes)")
    flip = np.concatenate([np.arange(N, 2 * N), np.arange(N)])
    return FermionMapSymmetry([(flip, np.where(np.arange(2 * N) < N, -1, 1), True, _ph_phase(N))], [eigval], ["PH"])


def PHRyQH(eigval: int) -> FermionMapSymmetry:
    r"""The product of ``PHQH`` and ``RyQH``, one particle-hole map: :math:`c^\dagger_{m\uparrow}\mapsto
    -(-1)^{m+s}c_{-m\downarrow}`, :math:`c^\dagger_{m\downarrow}\mapsto(-1)^{m+s}c_{-m\uparrow}`. Both factors send
    :math:`L^+\to-L^-`, so it commutes with every rotation: it keeps :math:`L_z` (unlike either factor) and is constant
    on a multiplet, with eigenvalue :math:`P(-1)^L` -- the particle-hole :math:`P` of PRX 13, 021009 at :math:`L=0`
    (same global phase as ``PHQH``). Requires half filling."""
    _check_eigval(eigval)
    sites = get_sites()
    N = sites.Nsites
    if sites.Ntotal != N:
        raise ValueError("particle-hole needs half filling (N particles in 2N modes)")
    o = np.arange(2 * N)
    f, j = o // N, o % N
    mirror = f * N + (N - 1 - j)
    flip_of = lambda q: (1 - q // N) * N + q % N
    sign_ph = lambda q: np.where(q < N, -1, 1)
    return FermionMapSymmetry([(flip_of(mirror), (-1) ** j * sign_ph(mirror), True, _ph_phase(N))], [eigval],
                              ["PHRy"])


def fuzzy_sphere_symmetry(z2: Optional[int] = None, ry: Optional[int] = None, ph: Optional[int] = None,
                          phry: Optional[int] = None) -> FuzzySphereSymmetry:
    """The product of the symmetries given an eigenvalue (1 or -1); those left as None are not imposed. With none,
    the identity. ``ry`` and ``ph`` apply at Lz = 0 only (each sends Lz to -Lz); ``phry`` at any Lz."""
    if None not in (ry, ph, phry):
        raise ValueError("ry, ph and phry together are redundant: phry = ph * ry")
    parts = [f(e) for f, e in ((Z2QH, z2), (RyQH, ry), (PHQH, ph), (PHRyQH, phry)) if e is not None]
    if not parts:
        return IdentityQH()
    symm = parts[0]
    for p in parts[1:]:
        symm = symm @ p
    return symm


def FlavourPermQH(eigval: int = 1) -> FuzzySphereSymmetry:
    """
    Particle-hole symmetry for fermion systems.

    :param eigval:
        An integer specifying the symmetry sector. The meaning of each number is

        - 1: Eigenvalue 1 after particle-hole inversion
        - 0: No particle-hole inversion
        - -1: Eigenvalue -1 after particle-hole inversion
    """
    if eigval not in (1, -1):
        raise ValueError("'eigval' of Z2Inversion should be 1 or -1.")
    sites = get_sites()
    N = sites.Nsites
    if sites.is_fermion:
        if eigval == 1:
            sector = 0
        elif eigval == -1:
            sector = 1
        else:
            return Identity()
        generator = np.concatenate([np.arange(N, 2 * N), np.arange(N)])
        return FuzzySphereSymmetry(generator, sector)